// Helper functions for easier data access
export const getProvinceNames = () => provinces.map(p => p.name);

export const getCitiesForProvince = (provinceName) => {
  const province = provinces.find(p => p.name === provinceName);
  return province ? province.cities : [];
};

export const isValidProvince = (provinceName) => {
  return provinces.some(p => p.name === provinceName);
};

// Convert to object format for backward compatibility
export const IranProvinces = provinces.reduce((acc, province) => {
  acc[province.name] = province.cities;
  return acc;
}, {});

export default provinces;

export function getCitiesOfProvince(provinceName) {
  const p = provinces.find(p => p.name === provinceName);
  return p ? p.cities : [];
}
